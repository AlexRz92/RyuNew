/** Devuelve las ciudades/municipios de un estado, ordenadas alfabéticamente. */
export function getCitiesByState(stateCode: string): City[] {
  return cities
    .filter((city) => city.stateCode === stateCode)
    .sort((a, b) => a.name.localeCompare(b.name, 'es'));
}
